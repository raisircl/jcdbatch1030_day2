# when you need to repeat a statement or set of statements again and again
# we use the loops to do that. There are two types of loops in python
# while loop and for loop
# today we will learn about while loop
# first of all we initialize a loop counter variable
# loop_counter=value
# while condition:
#     statement(s)
#     incr / decr loop_counter  

i=1 # set the loop counter variable to 1
while i<=5:
    print(f"{i}. Hello User!")
    i=i+1

